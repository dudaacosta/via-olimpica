// Base real/acumulativa da OBMEP para o Via Olímpica.
// Gerada a partir da lista-base de conteúdos OBMEP fornecida pela usuária.
//
// Lógica principal:
// - gradeOrigem: ano/série em que o conteúdo aparece originalmente na sequência de estudos.
// - gradeAlvo: ano/série do aluno que receberá o conteúdo no cronograma.
// - Um aluno de ano mais avançado recebe conteúdos de seu ano + conteúdos dos anos anteriores como revisão/base.
// - Exemplo: gradeAlvo "3em" recebe conteúdos de 6ano, 7ano, 8ano, 9ano, 1em, 2em, 3em e tópicos adicionais.
//
// Atenção:
// - Não altere os IDs sem atualizar a lógica do cronograma.
// - O item "Princípios Básicos de Contagem" aparece duas vezes na lista original do 2º EM e foi mantido duas vezes.
// - Total: 82 conteúdos únicos; ao expandir para gradeAlvo, a base acumulada tem 312 combinações.

