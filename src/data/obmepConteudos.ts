function gradeIndex(grade: GradeId): number {
  return gradeOrder.indexOf(grade);
}

function conteudoAplicaAoAno(item: ConteudoObmepUnico, gradeAlvo: GradeId): boolean {
  if (item.gradeOrigem === "adicional") return true;
  return gradeIndex(item.gradeOrigem) <= gradeIndex(gradeAlvo);
}

function getTipoConteudo(item: ConteudoObmepUnico, gradeAlvo: GradeId): TipoConteudo {
  if (item.gradeOrigem === "adicional") return "Complementar";
  if (item.gradeOrigem === gradeAlvo) return "Essencial do ano";
  return "Revisão/base acumulada";
}

function getPrioridadeParaCronograma(item: ConteudoObmepUnico, gradeAlvo: GradeId): Prioridade {
  const tipoConteudo = getTipoConteudo(item, gradeAlvo);
  if (tipoConteudo === "Essencial do ano") return item.prioridadeBase;
  if (tipoConteudo === "Complementar") return "Média";
  // Conteúdo de anos anteriores entra como revisão/base. Mantemos no máximo Média para não dominar o cronograma.
  return item.prioridadeBase === "Alta" ? "Média" : item.prioridadeBase;
}

export function getObmepConteudosPorGrade(gradeAlvo: GradeId): ConteudoObmepCronograma[] {
  return obmepConteudosUnicos
    .filter((item) => conteudoAplicaAoAno(item, gradeAlvo))
    .map((item) => ({
      ...item,
      gradeAlvo,
      anoAlvoNome: gradeLabels[gradeAlvo],
      prioridade: getPrioridadeParaCronograma(item, gradeAlvo),
      tipoConteudo: getTipoConteudo(item, gradeAlvo),
    }))
    .sort((a, b) => {
      if (a.ordemSugerida !== b.ordemSugerida) return a.ordemSugerida - b.ordemSugerida;
      return a.contentId.localeCompare(b.contentId);
    });
}

export function getConteudosPorOlimpiadaEAno(
  olympiadId: string,
  gradeAlvo: GradeId,
): ConteudoObmepCronograma[] {
  if (olympiadId !== "obmep") return [];
  return getObmepConteudosPorGrade(gradeAlvo);
}

export const obmepConteudos: ConteudoObmepCronograma[] = gradeOrder.flatMap((grade) =>
  getObmepConteudosPorGrade(grade),
);

export const resumoObmepPorGrade = gradeOrder.map((grade) => ({
  grade,
  anoEscolar: gradeLabels[grade],
  quantidadeConteudos: getObmepConteudosPorGrade(grade).length,
}));
